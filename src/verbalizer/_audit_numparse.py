add(900,"дев'ятсот","дев'ятисот","дев'ятистам","дев'ятьмастами","дев'ятистах")
for n, base in [(100,"сот"),(200,"двохсот"),(300,"трьохсот"),(400,"чотирьохсот"),(500,"п'ятисот"),
                (600,"шестисот"),(700,"семисот"),(800,"восьмисот"),(900,"дев'ятисот")]:
    add(n, *_forms(base, ORD_SUF))
# ordinals
for n, base in [(1,"перш"),(2,"друг"),(3,"трет"),(4,"четверт"),(5,"п'ят"),(6,"шост"),
                (7,"сьом"),(8,"восьм"),(9,"дев'ят"),(10,"десят"),(40,"сороков"),(90,"дев'яност")]:
    add(n, *_forms(base, ORD_SUF))

SCALES = {}
for w in ["тисяча","тисячі","тисяч","тисячу","тисячею","тисячам","тисячами","тисячах","тисячний","тисячна"]:
    SCALES[w] = 1000
for w in ["мільйон","мільйона","мільйони","мільйонів","мільйону","мільйоном","мільйонах","мільйонами","мільйонам"]:
    SCALES[w] = 10**6
for w in ["мільярд","мільярда","мільярди","мільярдів","мільярду","мільярдом","мільярдах","мільярдам","мільярдами"]:
    SCALES[w] = 10**9
for w in ["трильйон","трильйона","трильйони","трильйонів","трильйонах","трильйонам"]:
    SCALES[w] = 10**12

WORD = re.compile(r"[А-Яа-яЇїІіЄєҐґ'’]+")

def parse_numbers(text):
    """Return integer values expressed by consecutive numeral words in `text`."""
    out, cur, total, active = [], 0, 0, False
    for raw in WORD.findall(text):
        w = raw.lower().replace("’", "'")
        if w in SCALES:
            cur = cur or 1
            total += cur * SCALES[w]
            cur = 0
            active = True
        elif w in UNITS:
            cur += UNITS[w]
            active = True
        else:
            if active:
                out.append(total + cur)
                cur, total, active = 0, 0, False
    if active:
        out.append(total + cur)
    return out
