"""Offline audit helper: parse Ukrainian numeral words back to integers.

QA/verification tool only. It never runs in the pipeline and produces no spoken
form -- it reads targets that already exist and checks them. Matching is on
whole words against an explicit closed-class inflection table, because prefix
matching makes ordinary words like "сторони" or "становила" look like numerals.
"""
import re

def _forms(stem, sufs):
    return {stem + s for s in sufs}

ORD_SUF = ["ий","а","е","є","ій","я","ього","ьої","ьому","ьою","ому","ого","ої","им","ою","і","их","ю","у"]
CASE = ["", "а", "о", "е", "и", "і", "у", "ю", "ої", "ій", "ого", "ому", "ім", "им",
        "ою", "ею", "их", "ими", "ох", "ом", "ма", "ьох", "ьом", "ьома", "ьма"]

UNITS = {}
def add(val, *words):
    for w in words:
        UNITS[w.replace("’", "'")] = val

add(0, "нуль", "нуля", "нулю", "нулем", "нулів")
add(1, "один","одна","одне","одно","одного","одної","однієї","одній","одному","одну","одним","однією","одні","одних","одними")
add(2, "два","дві","двох","двом","двома","двоє","двійко")
add(3, "три","трьох","трьом","трьома","троє")
add(4, "чотири","чотирьох","чотирьом","чотирма","чотирьома","четверо")
add(5, "п'ять","п'яти","п'ятьох","п'ятьом","п'ятьма","п'ятьома","п'ятеро")
add(6, "шість","шести","шістьох","шістьом","шістьма","шістьома","шестеро")
add(7, "сім","семи","сімох","сімом","сімома","сьома","семеро")
add(8, "вісім","восьми","вісьмох","вісьмом","вісьма","вісьмома","восьмеро")
add(9, "дев'ять","дев'яти","дев'ятьох","дев'ятьом","дев'ятьма","дев'ятеро")
add(10,"десять","десяти","десятьох","десятьом","десятьма","десятеро")
for n, base in [(11,"одинадцят"),(12,"дванадцят"),(13,"тринадцят"),(14,"чотирнадцят"),
                (15,"п'ятнадцят"),(16,"шістнадцят"),(17,"сімнадцят"),(18,"вісімнадцят"),
                (19,"дев'ятнадцят"),(20,"двадцят"),(30,"тридцят")]:
    add(n, *_forms(base, ["ь","и","ьох","ьом","ьма","ьома","е","ий","а","ому","ій","ого","им",
                          "их","ими","і","у","ої","ою"]))
add(40,"сорок","сорока")
for n, base in [(50,"п'ятдесят"),(60,"шістдесят"),(70,"сімдесят"),(80,"вісімдесят")]:
    add(n, *_forms(base, ["","и","ьох","ьом","ьма","ьома","ий","ому","ої","ій","ого",
                          "их","им","ими","а","е","і","у","ою"]))
add(90,"дев'яносто","дев'яноста")
for _w in ["двотисячний","двотисячна","двотисячному","двотисячній","двотисячного","двотисячом",
           "двотисячні","двотисячних","двотисячними","двотисячне","двотисячну","двотисячної"]:
    UNITS[_w]=2000
add(100,"сто","ста","стам","стами","стах")
add(200,"двісті","двохсот","двомстам","двомастами","двохстах","двомста")
add(300,"триста","трьохсот","трьомстам","трьомастами","трьохстах","трьомста")
add(400,"чотириста","чотирьохсот","чотирьомстам","чотирмастами","чотирьохстах")
add(500,"п'ятсот","п'ятисот","п'ятистам","п'ятьмастами","п'ятистах","п'ятьомстам")
add(600,"шістсот","шестисот","шестистам","шістьмастами","шестистах","шістьомстам")
add(700,"сімсот","семисот","семистам","сімомастами","семистах")
