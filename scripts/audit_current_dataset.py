"""Audit prepared Parquet splits and write reproducible JSON/Markdown reports."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import pyarrow.parquet as pq


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.verbalizer.data.audit import audit_rows_by_split, canonical_source  # noqa: E402


DEFAULT_SPLITS = {
    "train": ROOT / "data/processed/train.parquet",
    "validation": ROOT / "data/processed/validation.parquet",
    "test_id": ROOT / "data/processed/test_id.parquet",
    "test_golden_weak": ROOT / "data/processed/test_golden_weak.parquet",
    "test_template_ood": ROOT / "data/processed/test_template_ood.parquet",
}
DEFAULT_REPORT = ROOT / "reports/current_dataset_audit.json"
DEFAULT_MARKDOWN = ROOT / "reports/current_dataset_audit.md"


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def read_rows(path: Path) -> list[dict[str, Any]]:
    return pq.read_table(path).to_pylist()


def leakage_report(split_rows: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    groups: dict[str, set[str]] = defaultdict(set)
    source_hashes: dict[str, set[str]] = defaultdict(set)
    for split, rows in split_rows.items():
        for row in rows:
            groups[str(row.get("group_id", ""))].add(split)
            source_hashes[canonical_source(str(row.get("source", "")))].add(split)

    group_overlap = {
        group: sorted(splits)
        for group, splits in groups.items()
        if group and len(splits) > 1
    }
    source_overlap = {
        source: sorted(splits)
        for source, splits in source_hashes.items()
        if source and len(splits) > 1
    }
    return {
        "group_overlap_count": len(group_overlap),
        "group_overlap_samples": dict(list(sorted(group_overlap.items()))[:10]),
        "canonical_source_overlap_count": len(source_overlap),
        "canonical_source_overlap_samples": dict(list(sorted(source_overlap.items()))[:10]),
        "passed": not group_overlap and not source_overlap,
    }


def markdown_report(report: dict[str, Any]) -> str:
    lines = [
        "# Current Dataset Audit",
        "",
        "Generated by `scripts/audit_current_dataset.py`.",
        "",
        "## Split summary",
        "",
        "| Split | Rows | Tier A | Tier B | Tier C | Tier D | Identity | Requires change |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for split, values in report["splits"].items():
        tiers = values["quality_tiers"]
        lines.append(
            f"| {split} | {values['rows']} | {tiers.get('A', 0)} | {tiers.get('B', 0)} | "
            f"{tiers.get('C', 0)} | {tiers.get('D', 0)} | {values['identity_rows']} | "
            f"{values['requires_change']} |"
        )
    lines.extend(
        [
            "",
            "## Leakage checks",
            "",
            f"- Group overlap: **{report['leakage']['group_overlap_count']}**.",
            f"- Canonical source overlap: **{report['leakage']['canonical_source_overlap_count']}**.",
            f"- Result: **{'PASS' if report['leakage']['passed'] else 'FAIL'}**.",
            "",
            "## Flags",
            "",
            "| Flag | Count |",
            "| --- | ---: |",
        ]
    )
    for flag, count in report["global"]["quality_flags"].items():
        lines.append(f"| `{flag}` | {count} |")
    lines.append("")
    return "\n".join(lines)


def audit(split_paths: dict[str, Path], report_path: Path, markdown_path: Path) -> dict[str, Any]:
    for path in split_paths.values():
        if not path.is_file():
            raise FileNotFoundError(path)
    raw_rows = {name: read_rows(path) for name, path in split_paths.items()}
    audited_rows, report = audit_rows_by_split(raw_rows)
    report["files"] = {
        name: {"path": str(path), "sha256": sha256_file(path), "rows": len(raw_rows[name])}
        for name, path in split_paths.items()
    }
    report["leakage"] = leakage_report(raw_rows)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    markdown_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_path.write_text(markdown_report(report), encoding="utf-8")
    return report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    for name, path in DEFAULT_SPLITS.items():
        parser.add_argument(f"--{name.replace('_', '-')}", type=Path, default=path)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--markdown", type=Path, default=DEFAULT_MARKDOWN)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when duplicate/template leakage is detected",
    )
    args = parser.parse_args()
    split_paths = {name: getattr(args, name.replace("-", "_")) for name in DEFAULT_SPLITS}
    result = audit(split_paths, args.report, args.markdown)
    print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))
    if args.check and not result["leakage"]["passed"]:
        raise SystemExit("dataset leakage check failed; see the generated report")


if __name__ == "__main__":
    main()
