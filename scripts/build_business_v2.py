def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT.parent / "eval-data/business_v2.jsonl")
    args = ap.parse_args()
    with args.out.open("w", encoding="utf-8") as f:
        for i, (src, tpl) in enumerate(LINES):
            refs = expand(tpl)
            f.write(json.dumps({"id": f"business2-{i + 1:02d}", "sentence": src, "reference": refs[0],
                                "references": refs, "marian": "", "gemma": "", "classes": ["business"]},
                               ensure_ascii=False) + "\n")
    print(len(LINES), "lines ->", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
